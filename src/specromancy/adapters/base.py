import json
import os
import shutil
import stat
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable, Protocol

from .. import __version__
from ..compatibility import ADAPTER_MANIFEST_VERSION, require_supported_version
